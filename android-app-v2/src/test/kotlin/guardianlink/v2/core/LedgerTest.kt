package guardianlink.v2.core

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertNotNull
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * Port of the TS core's `test/ledger.test.ts`, plus cross-implementation
 * known-answer vectors: the expected hashes below were produced by the
 * verified TypeScript core itself (same fixed clock, same inputs), so a
 * green run proves the Kotlin canonical serialization + hash chain are
 * byte-compatible with the TS core.
 */
class LedgerTest {

    @Test
    fun `hash chain verifies and detects tampering`() {
        val (h, _) = makeHarness()
        h.say("I took my evening dose.")
        h.say("The cabinet job is on schedule.")
        assertTrue(h.ledger.verifyChain())
        val tampered = h.ledger.events().map { it.copy(claim = "forged claim") }
        assertFalse(Ledger.verifyChainOf(tampered))
        assertTrue(h.audit.verify())
    }

    @Test
    fun `append-only - retraction is a new event, the original remains`() {
        val (h, _) = makeHarness()
        val r = h.say("The cabinet job is on schedule.")
        val originalId = r.admittedEventIds[0]
        val countBefore = h.ledger.allEvents().size
        h.say("Retract what I said about the cabinet job")
        assertTrue(h.ledger.allEvents().size > countBefore)
        val original = h.ledger.get(originalId)
        assertNotNull(original)
        assertEquals("The cabinet job is on schedule", original!!.claim)
        assertTrue(h.ledger.isRetracted(originalId))
        assertFalse(h.ledger.liveEvents().any { it.id == originalId })
    }

    @Test
    fun `delta - four values are distinct and never collapsed`() {
        val (h, _) = makeHarness()
        // unknown: no evidence
        assertEquals(Delta.UNKNOWN, h.questions.get("position")!!.current.delta)
        // distinguished: one source
        h.admit(AdmitInput(kind = EventKind.USER_REPORT, topic = "location", claim = "At Home", source = "sovereign"))
        assertEquals(Delta.DISTINGUISHED, h.questions.get("position")!!.current.delta)
        // equivalent: a second independent source agrees
        h.admitSensor("location", "location", "At Home", confidence = 0.95)
        assertEquals(Delta.EQUIVALENT, h.questions.get("position")!!.current.delta)
        // inapplicable: declared by system markers on every dependency — not inferred from absence
        val (h2, _) = makeHarness()
        for (topic in listOf("location", "medication", "state", "collector")) {
            h2.admit(AdmitInput(kind = EventKind.SYSTEM, topic = topic, claim = "__not_applicable__", source = "system"))
        }
        assertEquals(Delta.INAPPLICABLE, h2.questions.get("position")!!.current.delta)
    }

    @Test
    fun `dependency tracking - irrelevant admissions do not recompute a question`() {
        val (h, _) = makeHarness()
        val rel = h.questions.get("relationships")!!
        val pos = h.questions.get("position")!!
        val relCount = rel.recomputeCount
        val posCount = pos.recomputeCount
        h.say("I took my evening dose.")
        assertTrue(pos.recomputeCount > posCount, "position depends on medication")
        assertEquals(relCount, rel.recomputeCount, "relationships does not")
    }

    @Test
    fun `inference is never promoted to observation`() {
        val (h, _) = makeHarness()
        h.plugs.register(
            AgentPlug(
                id = "a1",
                name = "A",
                roles = listOf(AgentRole.ANALYST),
                contextScopes = listOf("location"),
                capabilityScopes = emptyList(),
                expiresAt = "2999-01-01T00:00:00.000Z",
            ),
        )
        h.plugs.submitEvidence("a1", topic = "location", claim = "Probably at home")
        val pos = h.questions.get("position")!!.current
        assertEquals(Basis.INFERRED, pos.basis)
        assertTrue(pos.text.contains("agent-derived"), "agent origin stays visible: ${pos.text}")
    }

    /* ---- Cross-implementation known-answer vectors (generated by the TS core) ---- */

    @Test
    fun `canonical serialization matches the TS core byte for byte`() {
        val sample: Map<String, Any?> = mapOf(
            "b" to 1,
            "a" to mapOf("d" to listOf(1, 2.5, "x"), "c" to true),
            "e" to null,
            "f" to 0.95,
        )
        assertEquals(
            "{\"a\":{\"c\":true,\"d\":[1,2.5,\"x\"]},\"b\":1,\"e\":null,\"f\":0.95}",
            Canonical.stringify(sample),
        )
        assertEquals(
            "498e491b5a6a70ccf9f4a01d993192083eb0e78ef0e7f2a0544b6fb3dee0beb6",
            Canonical.sha256Hex("guardianlink-v0.2"),
        )
    }

    @Test
    fun `ledger hash matches the TS core for the identical first event`() {
        val clock = TestClock("2026-10-23T14:00:00.000Z")
        val ledger = Ledger("sovereign-device", clock)
        val ev = ledger.admit(
            AdmitInput(
                kind = EventKind.USER_REPORT,
                topic = "medication.dose",
                claim = "I took my evening dose",
                source = "sovereign",
            ),
        )
        // Produced by the TypeScript Ledger for the identical input and clock.
        assertEquals("23a9d4873e20c46d095e6c7dc4936d414e86a62f653b0a0f91e8c08bca2f7a8b", ev.hash)
    }

    @Test
    fun `audit hash matches the TS core for the identical first entry`() {
        val clock = TestClock("2026-10-23T14:00:00.000Z")
        val audit = AuditLog(clock)
        val entry = audit.record(
            "sovereign",
            "test_action",
            mapOf("n" to 1, "s" to "x", "list" to listOf("a", "b"), "nested" to mapOf("k" to 2.5)),
        )
        // Produced by the TypeScript AuditLog for the identical input and clock.
        assertEquals("638c3681eed5eba7ebfe9a1789e13886ed31d3d7758654ef9869e6bda8f445bb", entry.hash)
    }
}
